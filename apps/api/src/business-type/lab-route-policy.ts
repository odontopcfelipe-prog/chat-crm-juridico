/**
 * F2 parte 4 do laboratório — POLÍTICA DE ROTAS: o que uma conta de laboratório
 * alcança na API. Lida pelo LabTenantGuard por 'Classe.metodo'.
 *
 * Critério: o laboratório é o mesmo sistema da clínica com outros nomes. Liberado
 * = o que ele usa (chat, contatos, cadastro do dentista-cliente, propostas, venda
 * rápida, caixa, financeiro, boletos, estoque, tarefas, ponto, equipe e as
 * configurações da PRÓPRIA conta). Fora: o que é só de clínica (odontograma,
 * anamnese, prontuário, retorno, portal, contrato/TCLE...), IA, configuração da
 * plataforma (GlobalSetting) e rota só do dono da plataforma.
 *
 * NEGAÇÃO POR PADRÃO: só passa o que está em ROTAS_DO_LABORATORIO. As duas listas
 * de negados existem para o spec route-policy.completeness saber o que já foi
 * DECIDIDO: handler novo que não está em lista nenhuma continua fechado para o
 * laboratório e aparece como "a classificar" no CI (só aviso — a clínica não
 * depende disto).
 */

/** Chave de um handler: 'Classe.metodo'. */
export function chaveDoHandler(classe: { name?: string } | undefined, handler: { name?: string } | undefined): string {
  return `${classe?.name ?? '?'}.${handler?.name ?? '?'}`;
}

